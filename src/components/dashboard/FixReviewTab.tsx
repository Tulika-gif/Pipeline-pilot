import React, { useState } from 'react';
import {
  GitPullRequest,
  CheckCircle2,
  AlertCircle,
  FileCode,
  Play,
  RotateCcw,
  Check,
  X,
  Copy,
  ExternalLink,
  ShieldCheck,
  Sparkles,
} from 'lucide-react';
import { NemotronInvestigation } from '../../types/pipeline';
import { useToast } from '../common/Toast';

interface FixReviewTabProps {
  investigation: NemotronInvestigation;
  onNavigateTab: (tab: string) => void;
}

export const FixReviewTab: React.FC<FixReviewTabProps> = ({
  investigation,
  onNavigateTab,
}) => {
  const [diffMode, setDiffMode] = useState<'split' | 'unified'>('split');
  const [validationState, setValidationState] = useState<'idle' | 'validating' | 'passed' | 'failed'>('passed');
  const [prCreated, setPrCreated] = useState<boolean>(false);
  const [isCopied, setIsCopied] = useState(false);
  const { showToast } = useToast();

  const handleRunValidation = () => {
    setValidationState('validating');
    showToast('Spinning up containerized sandbox for pre-flight validation...', {
      type: 'info',
    });
    setTimeout(() => {
      setValidationState('passed');
      showToast('Pre-flight validation passed in 1.4s', {
        type: 'success',
        description: 'Mock pytest run completed with 42 passed tests and zero failures.',
      });
    }, 1500);
  };

  const handleApprovePR = () => {
    setPrCreated(true);
    showToast('Created Pull Request #412: fix(ci): add requests dependency', {
      type: 'success',
      description: 'Branch pilot/fix-requests-step pushed to origin.',
    });
  };

  const handleCopyCode = () => {
    navigator.clipboard.writeText(investigation.fixDiff.fixedCode);
    setIsCopied(true);
    showToast('Proposed YAML patch copied to clipboard');
    setTimeout(() => setIsCopied(false), 2000);
  };

  return (
    <div className="space-y-6">
      {/* Top Status & Action Bar */}
      <div className="bg-white rounded-2xl p-5 border border-[#E5DFF5] shadow-xs flex flex-wrap items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="text-sm font-bold text-[#211D35] flex items-center gap-2">
              <FileCode className="w-4 h-4 text-[#6C45F5]" />
              {investigation.fixDiff.filePath}
            </span>
            <span className="text-xs font-mono px-2 py-0.5 rounded bg-[#EDE7FF] text-[#6C45F5] font-semibold">
              YAML Fix
            </span>
          </div>
          <p className="text-xs text-[#716B86]">
            Generated by NVIDIA Nemotron to fix missing dependency in workflow runner
          </p>
        </div>

        {/* Action Controls */}
        <div className="flex flex-wrap items-center gap-2 sm:gap-3">
          {/* View mode toggle */}
          <div className="flex items-center p-1 bg-[#F5F2FF] rounded-xl border border-[#E5DFF5] text-xs">
            <button
              onClick={() => setDiffMode('split')}
              className={`px-3 py-1.5 rounded-lg font-semibold transition-colors cursor-pointer ${
                diffMode === 'split' ? 'bg-white text-[#6C45F5] shadow-xs' : 'text-[#716B86]'
              }`}
            >
              Side-by-Side
            </button>
            <button
              onClick={() => setDiffMode('unified')}
              className={`px-3 py-1.5 rounded-lg font-semibold transition-colors cursor-pointer ${
                diffMode === 'unified' ? 'bg-white text-[#6C45F5] shadow-xs' : 'text-[#716B86]'
              }`}
            >
              Unified Diff
            </button>
          </div>

          <button
            onClick={handleCopyCode}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-[#E5DFF5] bg-white hover:bg-[#F5F2FF] text-[#211D35] font-medium text-xs transition-colors cursor-pointer"
          >
            {isCopied ? <Check className="w-3.5 h-3.5 text-[#20A878]" /> : <Copy className="w-3.5 h-3.5 text-[#716B86]" />}
            <span>{isCopied ? 'Copied' : 'Copy Patch'}</span>
          </button>

          <button
            onClick={handleRunValidation}
            disabled={validationState === 'validating'}
            className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl border border-[#6C45F5]/30 bg-[#EDE7FF]/60 hover:bg-[#EDE7FF] text-[#6C45F5] font-semibold text-xs transition-colors cursor-pointer disabled:opacity-50"
          >
            <Play className={`w-3.5 h-3.5 ${validationState === 'validating' ? 'animate-spin' : ''}`} />
            <span>{validationState === 'validating' ? 'Validating Sandbox...' : 'Run Dry-Run'}</span>
          </button>

          {!prCreated ? (
            <button
              onClick={handleApprovePR}
              className="flex items-center gap-2 px-4 py-1.5 rounded-xl text-xs font-semibold text-white bg-gradient-to-r from-[#6C45F5] to-[#21164F] shadow-sm hover:shadow-md transition-all cursor-pointer whitespace-nowrap"
            >
              <GitPullRequest className="w-3.5 h-3.5" />
              <span>Approve &amp; Open PR</span>
            </button>
          ) : (
            <div className="flex items-center gap-2 px-3.5 py-1.5 rounded-xl text-xs font-semibold text-[#20A878] bg-[#20A878]/10 border border-[#20A878]/20">
              <CheckCircle2 className="w-4 h-4" />
              <span>PR #412 Created</span>
            </div>
          )}
        </div>
      </div>

      {/* Validation Sandbox Status Strip */}
      <div className="bg-[#21164F] text-white rounded-2xl p-4 border border-[#6C45F5]/30 flex flex-wrap items-center justify-between gap-3 text-xs">
        <div className="flex items-center gap-3">
          <div className="w-7 h-7 rounded-lg bg-emerald-500/20 text-[#20A878] flex items-center justify-center">
            <ShieldCheck className="w-4 h-4" />
          </div>
          <div>
            <span className="font-bold text-[#EDE7FF] block">Pre-Flight Dry-Run Validation</span>
            <span className="text-white/70">
              {investigation.validationMessage}
            </span>
          </div>
        </div>

        <div className="flex items-center gap-3 font-mono text-[11px] text-white/80">
          <span className="text-[#20A878] font-bold">Status: READY</span>
          <span>·</span>
          <span>Target: runner-linux-amd64</span>
        </div>
      </div>

      {/* Side-by-Side or Unified Diff Viewer */}
      {diffMode === 'split' ? (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
          {/* Left Panel: Original Workflow */}
          <div className="bg-white rounded-2xl border border-[#E5DFF5] shadow-xs overflow-hidden flex flex-col">
            <div className="p-3 bg-[#F5F2FF] border-b border-[#E5DFF5] flex items-center justify-between">
              <span className="text-xs font-bold text-[#716B86] flex items-center gap-1.5">
                <span className="w-2 h-2 rounded-full bg-[#E5485D]" />
                Original Workflow (Failing)
              </span>
              <span className="text-[11px] font-mono text-[#716B86]">commit a1b2c3d</span>
            </div>

            <div className="p-4 font-mono text-xs overflow-x-auto leading-relaxed bg-white">
              <pre className="text-[#211D35]">
                {`      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip`}
              </pre>
              <div className="bg-[#E5485D]/10 text-[#E5485D] px-2 py-0.5 rounded my-1 font-semibold flex items-center justify-between">
                <span>-         pip install pytest pytest-cov pydantic</span>
                <span className="text-[10px] text-[#E5485D]/80">Missing requests</span>
              </div>
              <pre className="text-[#211D35]">
                {`
      - name: Run unit tests
        run: |
          pytest tests/unit -v`}
              </pre>
            </div>
          </div>

          {/* Right Panel: Proposed Fix (NVIDIA Nemotron) */}
          <div className="bg-white rounded-2xl border border-[#6C45F5]/30 shadow-xs overflow-hidden flex flex-col">
            <div className="p-3 bg-[#EDE7FF]/60 border-b border-[#6C45F5]/20 flex items-center justify-between">
              <span className="text-xs font-bold text-[#6C45F5] flex items-center gap-1.5">
                <span className="w-2 h-2 rounded-full bg-[#20A878]" />
                Proposed Fix (NVIDIA Nemotron)
              </span>
              <span className="text-[11px] font-mono text-[#6C45F5] font-semibold">
                +4 lines added
              </span>
            </div>

            <div className="p-4 font-mono text-xs overflow-x-auto leading-relaxed bg-white">
              <pre className="text-[#211D35]">
                {`      - name: Install dependencies
        run: |
          python -m pip install --upgrade pip`}
              </pre>
              <div className="bg-[#20A878]/10 text-[#20A878] px-2 py-0.5 rounded my-0.5 font-semibold">
                +         if [ -f requirements.txt ]; then pip install -r requirements.txt; fi
              </div>
              <div className="bg-[#20A878]/10 text-[#20A878] px-2 py-0.5 rounded my-0.5 font-semibold">
                +         pip install pytest pytest-cov pydantic requests&gt;=2.31.0
              </div>
              <div className="bg-[#20A878]/10 text-[#20A878] px-2 py-0.5 rounded my-0.5 font-semibold">
                +     - name: Verify dependency integrity
              </div>
              <div className="bg-[#20A878]/10 text-[#20A878] px-2 py-0.5 rounded my-0.5 font-semibold">
                +       run: python -c &quot;import requests, pydantic; print(&apos;All core modules resolved&apos;)&quot;
              </div>
              <pre className="text-[#211D35]">
                {`
      - name: Run unit tests
        run: |
          pytest tests/unit -v`}
              </pre>
            </div>
          </div>
        </div>
      ) : (
        /* Unified Diff View */
        <div className="bg-white rounded-2xl border border-[#E5DFF5] shadow-xs overflow-hidden">
          <div className="p-3 bg-[#F5F2FF] border-b border-[#E5DFF5] text-xs font-bold text-[#716B86]">
            Unified Patch Diff: {investigation.fixDiff.filePath}
          </div>
          <div className="p-4 font-mono text-xs overflow-x-auto divide-y divide-[#E5DFF5]/40 leading-relaxed">
            {investigation.fixDiff.diffLines.map((line, idx) => (
              <div
                key={idx}
                className={`py-1 px-2 flex items-start gap-4 ${
                  line.type === 'remove'
                    ? 'bg-[#E5485D]/10 text-[#E5485D] font-semibold'
                    : line.type === 'add'
                    ? 'bg-[#20A878]/10 text-[#20A878] font-semibold'
                    : 'text-[#716B86]'
                }`}
              >
                <div className="w-12 select-none flex justify-between text-[11px] opacity-60">
                  <span>{line.lineNumOriginal || ' '}</span>
                  <span>{line.lineNumFixed || ' '}</span>
                </div>
                <div className="flex-1 whitespace-pre">{line.content}</div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Review Actions Footer */}
      <div className="bg-white rounded-2xl p-5 border border-[#E5DFF5] shadow-xs flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 rounded-xl bg-[#EDE7FF] flex items-center justify-center text-[#6C45F5]">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <span className="text-xs font-bold text-[#211D35] block">
              Confidence Score: {investigation.confidence}%
            </span>
            <span className="text-[11px] text-[#716B86]">
              All security scanners verified clean. Zero permission elevation requested.
            </span>
          </div>
        </div>

        <div className="flex items-center gap-3">
          <button
            onClick={() => {
              showToast('Feedback submitted to Nemotron continuous learning pipeline');
              onNavigateTab('overview');
            }}
            className="px-4 py-2 rounded-xl text-xs font-semibold text-[#716B86] hover:text-[#E5485D] hover:bg-[#E5485D]/5 border border-[#E5DFF5] transition-colors cursor-pointer"
          >
            Reject Fix
          </button>

          {!prCreated ? (
            <button
              onClick={handleApprovePR}
              className="px-5 py-2 rounded-xl text-xs font-semibold text-white bg-gradient-to-r from-[#6C45F5] to-[#21164F] shadow-sm hover:shadow-md transition-all cursor-pointer whitespace-nowrap"
            >
              Approve &amp; Open PR
            </button>
          ) : (
            <button
              onClick={() => onNavigateTab('workflows')}
              className="px-5 py-2 rounded-xl text-xs font-semibold text-white bg-[#20A878] hover:bg-[#1b8e66] transition-colors cursor-pointer whitespace-nowrap"
            >
              Back to Workflow Runs
            </button>
          )}
        </div>
      </div>
    </div>
  );
};
